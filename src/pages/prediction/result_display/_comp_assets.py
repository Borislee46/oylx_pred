def click_js():
    return (
        "<script>(function(){"
        "var D=window.parent.document;var attached=new WeakSet();"
        "var attachedHover=new WeakSet();var activeGroup=null;var collapseTimer=null;"
        "function S(n){"
        "D.querySelectorAll('.hk-comp-gap').forEach(function(g){"
        "g.style.display=g.getAttribute('data-school')===n?'block':'none';});"
        "D.querySelectorAll('.hk-comp-narrative').forEach(function(t){"
        "t.style.display=t.getAttribute('data-school')===n?'block':'none';});"
        "var hdr=D.getElementById('hk-comp-cur');var tb=D.getElementById('hk-comp-cur-tier');"
        "D.querySelectorAll('.hk-comp-dot').forEach(function(d){"
        "var m=d.getAttribute('data-school')===n;d.classList.toggle('hk-comp-sel',m);"
        "if(m){if(hdr)hdr.textContent=n;"
        "var tl=d.getAttribute('data-tier');var tc=d.getAttribute('data-tiercolor');"
        "if(tb){if(tl){tb.textContent=tl;tb.style.background=tc;tb.style.display='inline-block';}"
        "else{tb.style.display='none';}}}"
        "d.setAttribute('aria-pressed',m?'true':'false');"
        "var c=d.querySelector('.hk-comp-circle');if(c){var bc=getComputedStyle(c).borderColor;"
        "c.style.boxShadow=m?'0 0 0 4px '+bc+'1a':'0 1px 3px rgba(0,0,0,0.06)';}});"
        "D.querySelectorAll('.hk-comp-chip').forEach(function(ch){"
        "var m=ch.getAttribute('data-school')===n;ch.classList.toggle('hk-comp-chip-sel',m);"
        "ch.setAttribute('aria-pressed',m?'true':'false');});}"
        "function bindDots(){"
        "D.querySelectorAll('.hk-comp-dot').forEach(function(d){"
        "if(attached.has(d))return;attached.add(d);"
        "d.addEventListener('click',function(e){e.stopPropagation();"
        "var s=this.getAttribute('data-school');if(s)S(s);});"
        "d.addEventListener('keydown',function(e){if(e.key==='Enter'||e.key===' '){"
        "e.preventDefault();var s=this.getAttribute('data-school');if(s)S(s);}});});}"
        "function bindChips(){"
        "D.querySelectorAll('.hk-comp-chip').forEach(function(ch){"
        "if(attached.has(ch))return;attached.add(ch);"
        "ch.addEventListener('click',function(e){e.stopPropagation();"
        "var s=this.getAttribute('data-school');if(s)S(s);});});}"
        "function bindHover(){"
        "D.querySelectorAll('.hk-comp-dot').forEach(function(d){"
        "if(attachedHover.has(d))return;attachedHover.add(d);"
        "d.addEventListener('mouseenter',function(){"
        "var g=this.getAttribute('data-group');"
        "if(!g)return;"
        "clearTimeout(collapseTimer);"
        "if(activeGroup===g)return;"
        "activeGroup=g;"
        "D.querySelectorAll('.hk-comp-dot[data-group=\"'+g+'\"]').forEach(function(dot){"
        "var exp=dot.getAttribute('data-expanded-top');"
        "if(exp)dot.style.top=exp;});});"
        "d.addEventListener('mouseleave',function(e){"
        "var g=this.getAttribute('data-group');"
        "if(!g)return;"
        "var toEl=e.relatedTarget;"
        "if(toEl&&toEl.closest){"
        "var toDot=toEl.closest('.hk-comp-dot');"
        "if(toDot&&toDot.getAttribute('data-group')===g)return;}"
        "collapseTimer=setTimeout(function(){"
        "if(activeGroup!==g)return;"
        "activeGroup=null;"
        "D.querySelectorAll('.hk-comp-dot[data-group=\"'+g+'\"]').forEach(function(dot){"
        "var def=dot.getAttribute('data-default-top');"
        "if(def)dot.style.top=def;});},200);});});}"
        "bindDots();bindHover();bindChips();"
        "var obs=new MutationObserver(function(){bindDots();bindHover();bindChips();});"
        "obs.observe(D.body,{childList:true,subtree:true});"
        "})();</script>"
    )
